def level_2_categories(categories):
  if categories in ['Company downsizing']:
    return 'Organizational Restructuring'
  if categories in ['Contract ended']:
    return 'Contract Expiration'
  if categories in ['Found a better opportunity','Lack of growth opportunities','Career change']:
    return 'Career & Compensation'
  if categories in ['Family commitments','Health reasons','Relocation','Personal reasons']:
    return 'Personal - Life Events'
  if categories in ['Retirement']:
    return 'Natural Attrition'
  else:
    return 'Unknown'

