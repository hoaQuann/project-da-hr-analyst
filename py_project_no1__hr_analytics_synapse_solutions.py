# Tạo hàm để chuẩn hóa tên cột
def remove_vietnamese_accents(text):
    """Hàm phụ trợ: Xóa dấu tiếng Việt bằng unicodedata"""
    if not isinstance(text, str):
        return text
    # 1. normalize('NFKD'): Tách ký tự gốc và dấu (Ví dụ: 'á' -> 'a' và dấu sắc)
    # 2. encode('ASCII', 'ignore'): Ép về chuẩn mã ASCII, tự động vứt bỏ các dấu không thuộc ASCII
    # 3. decode('utf-8'): Chuyển ngược lại thành chuỗi String bình thường
    return unicodedata.normalize('NFKD', text).encode('ASCII', 'ignore').decode('utf-8')

def chuan_hoa_ten_cot(df):
    """Hàm chuẩn hóa toàn bộ tên cột trong DataFrame"""
    # 1. Chuyển thành chữ thường
    cols = df.columns.str.lower()

    # 2. (Tùy chọn nâng cao) Xóa bỏ các ký tự đặc biệt không phải chữ/số (như %, (), dấu phẩy...)
    cols = cols.str.replace(r'[^\w\s]', '', regex=True)

    # 3. Xóa khoảng trắng 2 đầu
    cols = cols.str.strip()

    # 4. Loại bỏ dấu tiếng Việt (Áp dụng hàm phụ trợ qua .map)
    cols = cols.map(remove_vietnamese_accents)

    # 5. Thay thế khoảng trắng ở giữa bằng dấu gạch dưới '_'
    cols = cols.str.replace(' ', '_', regex=False)

    # 6. Gán lại tên cột cho DataFrame
    df.columns = cols
    return df

