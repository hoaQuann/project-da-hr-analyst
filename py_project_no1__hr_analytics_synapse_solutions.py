import numpy as np

def check_data_consistency(df_Hire, df_Comp):
    """
    Hàm kiểm tra tính đồng nhất 100% của các cột bị trùng lặp giữa 2 bảng.

    LÝ DO & PHÂN TÍCH THUẬT TOÁN:
    - Tại sao dùng pd.merge: Để đảm bảo so sánh đúng người (cùng Employee_ID),
      tránh trường hợp hai bảng bị sắp xếp lộn xộn thứ tự dòng.
    - Ưu điểm: Tuyệt đối chính xác, an toàn, hỗ trợ xuất ra các dòng bị lỗi.
    - Tối ưu hóa hiệu năng: Thay vì Merge toàn bộ bảng (tốn RAM), chúng ta
      chỉ 'select' đúng Khóa chính và các cột cần so sánh. Tốc độ thực thi
      O(N log N) nhanh gấp hàng trăm lần so với việc dùng iterrows() O(N^2).
    """
    print("--- BẮT ĐẦU KIỂM TRA ĐỒNG NHẤT DỮ LIỆU ---")

    # Bước 1: Merge 2 bảng (Chỉ lấy các cột cần thiết để tối ưu bộ nhớ)
    # Hậu tố _hiring và _comp sẽ được tự động thêm vào tên cột nếu trùng nhau
    df_merged = pd.merge(
        df_Hire[['Employee_ID', 'Source of Hire', 'Starting Salary']],
        df_Comp[['Employee_ID', 'Source of Hire', 'Starting Salary']],
        on='Employee_ID',
        how='inner',
        suffixes=('_hiring', '_comp')
    )

    # Bước 2: So sánh bằng Vectorization (Rất nhanh)
    # Toán tử == sẽ trả về một Series gồm True/False. Hàm .all() kiểm tra xem tất cả có phải True hay không.
    is_source_match = (df_merged['Source of Hire_hiring'] == df_merged['Source of Hire_comp']).all()
    is_salary_match = (df_merged['Starting Salary_hiring'] == df_merged['Starting Salary_comp']).all()

    # Bước 3: In kết quả
    print(f"1. Cột 'Source of Hire' khớp 100% không? -> {'CÓ' if is_source_match else 'KHÔNG'}")
    print(f"2. Cột 'Starting Salary' khớp 100% không? -> {'CÓ' if is_salary_match else 'KHÔNG'}")

    # Bước 4: Xử lý ngoại lệ (Trích xuất dữ liệu lỗi)
    if not (is_source_match and is_salary_match):
        print("\n[CẢNH BÁO] Phát hiện dữ liệu mâu thuẫn! Dưới đây là các dòng bị lệch:")

        # Tìm các dòng có Source hoặc Salary không khớp
        mismatch_condition = (
            (df_merged['Source of Hire_hiring'] != df_merged['Source of Hire_comp']) |
            (df_merged['Starting Salary_hiring'] != df_merged['Starting Salary_comp'])
        )

        df_errors = df_merged[mismatch_condition]
        print(df_errors.head()) # In ra 5 dòng lỗi đầu tiên để kiểm tra
    else:
        print("\n[KẾT LUẬN TỐI ƯU] Dữ liệu khớp 100%. ĐỀ XUẤT: Bạn CÓ THỂ LOẠI BỎ bảng 'Hiring.csv' khi xây dựng Model trong Power BI để tránh dư thừa.")


